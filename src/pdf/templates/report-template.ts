// Normalizes the single space between a currency symbol and its amount
// (e.g. collapses "৳  1,234" -> "৳ 1,234"). Handles every symbol in
// src/constants/currency.ts so the PDF stays correct regardless of which
// currency the user has selected, not just BDT.
function money(value: string): string {
  return value.replace(/([৳$€﷼])\s*/g, "$1 ");
}

function esc(value: unknown): string { return escapeHtml(String(value ?? "")); }

function chartSvg(title: string, points: ReportChartPoint[], kind: "line" = "line", accent = BLUE): string {
  const width = 500, height = 205, left = 44, right = 18, top = 32, bottom = 42;
  const plotW = width - left - right, plotH = height - top - bottom;
  const vals = points.map(p => Number(p.value) || 0);
  const max = Math.max(1, ...vals);
  const n = Math.max(points.length, 1);
  const x = (i: number) => left + (n === 1 ? plotW / 2 : (i * plotW) / (n - 1));
  const y = (v: number) => top + plotH - (v / max) * plotH;
  const labels = points.map(p => esc(p.label));
  const grid = [0, .25, .5, .75, 1].map(f => {
    const yy = top + plotH - f * plotH;
    const val = Math.round(max * f).toLocaleString("en-US");
    return `<line x1="${left}" y1="${yy}" x2="${width-right}" y2="${yy}" stroke="${BORDER}" stroke-width="1"/><text x="${left-6}" y="${yy+3}" text-anchor="end" font-size="8" fill="${MUTED}">${val}</text>`;
  }).join("");
  let series = "";
  if (false) {
    const gap = 8, bw = Math.max(8, Math.min(38, plotW / n - gap));
    series = points.map((p,i) => {
      const xx = n === 1 ? left + plotW/2 - bw/2 : x(i) - bw/2;
      const yy = y(Number(p.value)||0), hh = top + plotH - yy;
      return `<rect x="${xx}" y="${yy}" width="${bw}" height="${hh}" rx="2" fill="${accent}"/><text x="${xx+bw/2}" y="${height-22}" text-anchor="middle" font-size="7" fill="${MUTED}">${labels[i]}</text>`;
    }).join("");
  } else {
    const poly = points.map((p,i) => `${x(i)},${y(Number(p.value)||0)}`).join(" ");
    series = `<polyline points="${poly}" fill="none" stroke="${accent}" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"/>` + points.map((p,i) => `<circle cx="${x(i)}" cy="${y(Number(p.value)||0)}" r="2.8" fill="white" stroke="${accent}" stroke-width="2"/><text x="${x(i)}" y="${height-22}" text-anchor="middle" font-size="7" fill="${MUTED}">${labels[i]}</text>`).join("");
  }
  return `<div class="chart"><div class="chart-title">${esc(title)}</div><svg viewBox="0 0 ${width} ${height}" preserveAspectRatio="none">${grid}${series}</svg></div>`;
}

function card(c: ReportSectionCard, labels: ReportLabels, accent = BLUE): string {
  // PHASE 10 UI AUDIT FIX: this used to infer "Business metric" vs
  // "Operational metric" by checking whether c.title (English) contained
  // substrings like "Value"/"Sales"/"Revenue" -- since card titles are
  // now translated via t() in reports-page.tsx, that match silently
  // never fired for bn/ar. reports-page.tsx now sets an explicit
  // `isBusinessMetric` flag per card instead of this being inferred from
  // display text.
  return `<div class="kpi"><div class="accent" style="background:${accent}"></div><div class="kpi-label">${esc(c.title)}</div><div class="kpi-value">${money(esc(c.value))}</div><div class="kpi-note">${esc(c.isBusinessMetric ? labels.businessMetric : labels.operationalMetric)}</div></div>`;
}

function cards(cardsData: ReportSectionCard[], labels: ReportLabels, accents?: string[]): string {
  return `<div class="kpi-grid">${cardsData.map((c,i)=>card(c, labels, accents?.[i] ?? BLUE)).join("")}</div>`;
}

function table(headers: string[], rows: string[][], numericCols: number[] = []): string {
  const isNum = (i: number) => numericCols.includes(i);
  return `<table><thead><tr>${headers.map((h,i)=>`<th class="${isNum(i)?"num":""}">${esc(h)}</th>`).join("")}</tr></thead><tbody>${rows.map(r=>`<tr>${r.map((v,i)=>`<td class="${isNum(i)?"num":""}">${i===r.length-1?money(esc(v)):esc(v)}</td>`).join("")}</tr>`).join("")}</tbody></table>`;
}

function header(data: ReportTemplateData): string {
  const contact = [data.companyAddress, data.companyPhone, data.companyEmail, data.companyWebsite].filter(Boolean).map(esc).join(" • ");
  return `<div class="header"><div class="brand">${data.logoDataUrl ? `<img src="${data.logoDataUrl}"/>` : ""}<div><div class="company">${esc(data.companyName)}</div><div class="erp">${esc(data.labels.erpSubtitle)}</div></div></div><div class="report-head"><div><div class="report-title">${esc(data.reportTitle)}</div><div class="report-label">${esc(data.reportLabel)}</div><div class="profile">${contact || esc(data.labels.companyProfileFallback)}</div></div><div class="meta"><b>${esc(data.labels.periodLabel)}</b> ${esc(data.dateRangeLabel)}<br/><b>${esc(data.labels.generatedLabel)}</b> ${esc(data.generatedAtLabel)}</div></div></div>`;
}

// Slim running header for every page after the first. The full header()
// above (logo + company block + report title + period/generated meta)
// is intentionally shown ONLY once, on page 1 -- repeating that full
// block on all 8 pages was wasting ~25mm of vertical space per page for
// no new information (the report title/date range/logo never change
// page to page) and was the reported bug. This keeps just enough
// context (company name + report title) to identify a page if it's
// viewed out of order, without re-showing the logo or duplicating the
// period/generated timestamps that are already on page 1.
function runningHeader(data: ReportTemplateData): string {
  return `<div class="running-header"><span class="running-company">${esc(data.companyName)}</span><span class="running-report">${esc(data.reportTitle)}</span></div>`;
}

function page(data: ReportTemplateData, title: string, content: string, pageNumber: number): string {
  const headerHtml = pageNumber === 1 ? header(data) : runningHeader(data);
  return `<section class="page">${headerHtml}<div class="page-title">${esc(title)}</div>${content}<div class="footer"><span>${esc(data.labels.footerAutoGenerated.replace("{company}", data.companyName))}</span><span>${esc(data.labels.pageWord)}-${pageNumber}</span></div></section>`;
}

